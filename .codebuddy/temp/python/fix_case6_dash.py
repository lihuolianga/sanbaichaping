total_before = 0
total_after = 0
for fname, reps in REP.items():
    p = os.path.join(case_dir, fname)
    text = open(p, encoding="utf-8-sig").read()
    before = text.count("——")
    total_before += before
    miss = []
    for old, new in reps:
        c = text.count(old)
        if c == 0:
            miss.append(old)
            continue
        text = text.replace(old, new)
    after = text.count("——")
    total_after += after
    if miss:
        buf.append(f"{fname}: 有 {len(miss)} 处未匹配!")
        for m in miss:
            buf.append(f"   MISS: {m[:60]}")
    # 写回（保留原BOM情况：utf-8-sig读取则写utf-8-sig）
    open(p, "w", encoding="utf-8-sig").write(text)
    buf.append(f"{fname}: 破折号 {before} -> {after}")

buf.append(f"\n合计: {total_before} -> {total_after}")
