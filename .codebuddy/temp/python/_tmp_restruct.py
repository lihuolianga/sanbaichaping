def cn(n):
    d = "零一二三四五六七八九"
    if n <= 10:
        return d[n] if n < 10 else "十"
    if n < 20:
        return "十" + d[n % 10]
    if n < 100:
        tens = n // 10
        ones = n % 10
        return d[tens] + "十" + (d[ones] if ones else "")
    return str(n)

def case_of(x):
    for cid, name, lo, hi in cases:
        if lo <= x <= hi:
            return cid, name, lo
    return None

def vol_of(x):
    for vname, lo, hi in vols:
        if lo <= x <= hi:
            return vname
    return None

renamed = 0
errors = []
samples = []

for vname, _, _ in vols:
    d = os.path.join(base, vname)
    if not os.path.isdir(d):
        continue
    for f in glob.glob(os.path.join(d, "*.md")):
        name = os.path.basename(f)
        m = re.match(r'^案件\d+-第(\d+)章_(.*)\.md$', name)
        if not m:
            errors.append((vname, name, "文件名无法解析"))
            continue
        x = int(m.group(1))
        title = m.group(2)
        r = case_of(x)
        if r is None:
            errors.append((vname, name, "章号无案件映射"))
            continue
        cid, cname, lo = r
        v = vol_of(x)
        if v is None:
            errors.append((vname, name, "章号无卷映射"))
            continue
        seq = x - lo + 1
        case_dir = "案件" + cn(cid) + " " + cname
        newname = "第" + cn(seq) + "章 " + title + ".md"
        target_dir = os.path.join(base, v, case_dir)
        os.makedirs(target_dir, exist_ok=True)
        newpath = os.path.join(target_dir, newname)
        if os.path.exists(newpath):
            errors.append((v, name, "目标已存在: " + newname))
            continue
        shutil.move(f, newpath)
        renamed += 1
        if len(samples) < 20:
            samples.append(f"{v}/{name}  ->  {v}/{case_dir}/{newname}")

print(f"移动重命名成功: {renamed}")
