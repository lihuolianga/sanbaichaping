def case_of(n):
    for cid, lo, hi in cases:
        if lo <= n <= hi:
            return cid
    return None

vols = ["第一卷","第二卷","第三卷","第四卷","第五卷","第六卷",
        "第七卷","第八卷","第九卷","第十卷","第十一卷","第十二卷"]

renamed = 0
skipped = 0
errors = []
examples = []

for v in vols:
    d = os.path.join(base, v)
    if not os.path.isdir(d):
        continue
    for f in glob.glob(os.path.join(d, "*.md")):
        name = os.path.basename(f)
        if name.startswith("案件"):
            skipped += 1
            continue
        m = re.match(r'^第(\d+)章', name)
        if not m:
            errors.append((v, name, "无法识别章号"))
            continue
        n = int(m.group(1))
        cid = case_of(n)
        if cid is None:
            errors.append((v, name, "找不到对应案件"))
            continue
        newname = f"案件{cid}-{name}"
        newpath = os.path.join(d, newname)
        if os.path.exists(newpath):
            errors.append((v, name, "目标已存在"))
            continue
        os.rename(f, newpath)
        renamed += 1
        if len(examples) < 15:
            examples.append(f"{v} | {name}  ->  {newname}")

print(f"重命名成功: {renamed}")
print(f"跳过(已有案件前缀): {skipped}")
print(f"错误/异常: {len(errors)}")
print("-" * 60)
for e in examples:
    print(e)
