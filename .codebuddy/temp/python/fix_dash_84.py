def main():
    # 第一阶段：读入全部文件并校验，确保所有替换对唯一且存在
    loaded = {}
    total = 0
    for ch, pairs in PLAN.items():
        path = find(ch)
        with open(path, encoding='utf-8') as f:
            text = f.read()
        for old, new in pairs:
            cnt = text.count(old)
            assert cnt == 1, '第%s章 %r 出现%d次' % (ch, old, cnt)
        loaded[ch] = (path, text, pairs)
        total += len(pairs)
    print('校验通过，共 %d 处' % total)

    # 第二阶段：全部校验通过后统一写回
    for ch, (path, text, pairs) in loaded.items():
        for old, new in pairs:
            text = text.replace(old, new, 1)
        with open(path, 'w', encoding='utf-8') as f:
            f.write(text)
        print('OK 第%s章 %d处' % (ch, len(pairs)))
    print('全部完成')


if __name__ == '__main__':
    main()
